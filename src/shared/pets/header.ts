  section("Setup and confirm codes");
  out.push(`#define PET_CODE_ALPHABET ${cString(CODE_ALPHABET)}`);
  out.push(`#define PET_SETUP_CODE_LENGTH ${SETUP_CODE_LENGTH}`);
  out.push(`#define PET_CONFIRM_CODE_LENGTH ${CONFIRM_CODE_LENGTH}`);
  out.push("");

  section("Set up over USB (pet-usb v1, src/usb.ts)");
  out.push(`#define PET_USB_VERSION ${PET_USB_VERSION}`);
  out.push(`#define PET_USB_PREFIX ${cString(PET_USB_PREFIX)}`);
  out.push(`#define PET_USB_PREFIX_LENGTH ${PET_USB_PREFIX.length}`);
  out.push(
    `#define PET_USB_MAX_LINE ${PET_USB_MAX_LINE} // bytes before the newline, the prefix included`,
  );
  out.push(
    `#define PET_USB_MAX_LINES_PER_SECOND ${PET_USB_MAX_LINES_PER_SECOND}`,
  );
  out.push(`#define PET_USB_BAUD ${PET_USB_BAUD}`);
  out.push(`#define PET_USB_VENDOR_ID ${usbId(PET_USB_VENDOR_ID)}`);
  out.push(`#define PET_USB_PRODUCT_ID ${usbId(PET_USB_PRODUCT_ID)}`);
  out.push(`#define PET_USB_MAX_NETWORKS ${PET_USB_MAX_NETWORKS}`);
  out.push(`#define PET_USB_SSID_MAX_BYTES ${PET_USB_SSID_MAX_BYTES}`);
  out.push(`#define PET_USB_PASSWORD_MIN_CHARS ${PET_USB_PASSWORD_MIN_CHARS}`);
  out.push(`#define PET_USB_PASSWORD_MAX_CHARS ${PET_USB_PASSWORD_MAX_CHARS}`);
  out.push(`#define PET_USB_PASSWORD_HEX_CHARS ${PET_USB_PASSWORD_HEX_CHARS}`);
  out.push(`#define PET_USB_FIRMWARE_MAX_CHARS ${PET_USB_FIRMWARE_MAX_CHARS}`);
  out.push(
    `#define PET_USB_OPEN_PASSWORD ${cString(PET_USB_OPEN_PASSWORD)} // the password token of an open network`,
  );
  for (const [name, word] of Object.entries(PET_USB_WORDS)) {
    out.push(`#define PET_USB_WORD_${macroName(name)} ${cString(word)}`);
  }
  idList(out, "PetUsbOp", "PET_USB_OP", PET_USB_OPS);
  idList(out, "PetUsbReply", "PET_USB_REPLY", PET_USB_REPLY_TYPES);
  idList(out, "PetUsbState", "PET_USB_STATE", PET_USB_STATES);
  idList(out, "PetUsbError", "PET_USB_ERROR", PET_USB_ERRORS);
  idList(out, "PetUsbRefusal", "PET_USB_REFUSAL", PET_USB_REFUSALS);
  out.push("");

  section("Set up over USB, version 2 (pet-usb v2, src/usb.ts)");
  out.push(
    `#define PET_USB2_VERSION ${PET_USB2_VERSION} // the first version that speaks server, wifi and start`,
  );
  out.push(
    `#define PET_USB2_NO_ADDRESS ${cString(PET_USB2_NO_ADDRESS)} // the address token of a computer with none to give`,
  );
  out.push(`#define PET_USB2_ADDRESS_MAX_CHARS ${PET_USB2_ADDRESS_MAX_CHARS}`);
  out.push(`#define PET_USB2_FINGERPRINT_CHARS ${PET_USB2_FINGERPRINT_CHARS}`);
  out.push(`#define PET_USB2_MAX_PORT ${PET_USB2_MAX_PORT}`);
  out.push(`#define PET_USB2_NAME_PREFIX ${cString(PET_USB2_NAME_PREFIX)}`);
