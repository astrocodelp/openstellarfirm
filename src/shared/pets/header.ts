  for (const [name, value] of Object.entries(PET_LIMITS)) {
    out.push(`#define PET_${upperSnake(name)} ${value}`);
  }
  out.push(
    `#define PET_ADPCM_SAMPLES_PER_BLOCK ${samplesPerBlock(PET_LIMITS.adpcmBlockAlign)}`,
  );
  out.push("");

  section("HTTP");
  for (const [name, value] of Object.entries(PET_HEADERS)) {
    out.push(`#define PET_HEADER_${upperSnake(name)} ${cString(value)}`);
  }
  out.push(
    `#define PET_AUDIO_UP_CONTENT_TYPE ${cString(PET_AUDIO_UP_CONTENT_TYPE)}`,
  );
  out.push(
    `#define PET_AUDIO_DOWN_CONTENT_TYPE ${cString(PET_AUDIO_DOWN_CONTENT_TYPE)}`,
  );
