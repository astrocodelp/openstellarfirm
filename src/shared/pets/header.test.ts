import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { decodeImaAdpcm } from "./adpcm";
import {
  ADPCM_VECTOR_SAMPLES,
  renderAdpcmVectorsHeader,
  renderProtocolHeader,
  renderUsbVectorsHeader,
} from "./header";
import { PET_LIMITS } from "./limits";
import { PET_LINES, PET_ROLE_IDS } from "./lines";
import { PET_ERRORS } from "./protocol";
import {
  PET_USB_ERRORS,
  PET_USB_OPS,
  PET_USB_REFUSALS,
  PET_USB_REPLY_TYPES,
  PET_USB_STATES,
} from "./usb";
import { PET_USB_REPLY_VECTORS, PET_USB_REQUEST_VECTORS } from "./usb-vectors";

const generated = join(
  import.meta.dirname,
  "../../../firmware/pet/include/generated",
);

const BANNER =
  "// Generated by src/shared/pets/header.ts (pnpm pets:header). Do not edit by hand.";

function committed(name: string): string {
  const path = join(generated, name);
  if (!existsSync(path)) {
    throw new Error(`${path} is missing. Run: pnpm pets:header`);
  }
  return readFileSync(path, "utf8");
}

describe("the committed headers have not drifted", () => {
  it("protocol.h is what the package renders", () => {
    // The failure message is the fix, so nobody edits the file by hand.
    expect(
      committed("protocol.h") === renderProtocolHeader(),
      "firmware/pet/include/generated/protocol.h is out of date. Run: pnpm pets:header",
    ).toBe(true);
  });

  it("adpcm_vectors.h is what the package renders", () => {
    expect(
      committed("adpcm_vectors.h") === renderAdpcmVectorsHeader(),
      "firmware/pet/include/generated/adpcm_vectors.h is out of date. Run: pnpm pets:header",
    ).toBe(true);
  });

  it("usb_vectors.h is what the package renders", () => {
    expect(
      committed("usb_vectors.h") === renderUsbVectorsHeader(),
      "firmware/pet/include/generated/usb_vectors.h is out of date. Run: pnpm pets:header",
    ).toBe(true);
  });
});

describe("protocol.h", () => {
  const text = renderProtocolHeader();

  it("starts with the banner and a pragma once", () => {
    const lines = text.split("\n");
    expect(lines[0]).toBe(BANNER);
    expect(lines[1]).toBe("#pragma once");
    expect(text.endsWith("\n")).toBe(true);
  });

  it("is plain ASCII with no tabs, trailing spaces or em dashes", () => {
    expect(text).toMatch(/^[\x20-\x7e\n]*$/);
    expect(text).not.toMatch(/ +\n/);
  });

  it("carries the protocol version and the hardware id", () => {
    expect(text).toContain("#define PET_PROTOCOL_VERSION 1\n");
    expect(text).toContain('#define PET_HARDWARE_ID "nano-esp32-v1"\n');
  });

  it("defines every limit with its value", () => {
    const names: Record<string, string> = {
      recordMaxSeconds: "PET_RECORD_MAX_SECONDS",
      uploadMaxBytes: "PET_UPLOAD_MAX_BYTES",
      silenceEndSeconds: "PET_SILENCE_END_SECONDS",
      upSampleRate: "PET_UP_SAMPLE_RATE",
      downSampleRate: "PET_DOWN_SAMPLE_RATE",
      adpcmBlockAlign: "PET_ADPCM_BLOCK_ALIGN",
      firstAnswerWaitSeconds: "PET_FIRST_ANSWER_WAIT_SECONDS",
      spokenLineMaxChars: "PET_SPOKEN_LINE_MAX_CHARS",
      spokenLineMaxSentences: "PET_SPOKEN_LINE_MAX_SENTENCES",
      workTitleMaxWords: "PET_WORK_TITLE_MAX_WORDS",
      savedNotesMax: "PET_SAVED_NOTES_MAX",
      turnsPerMinute: "PET_TURNS_PER_MINUTE",
      turnsPerDay: "PET_TURNS_PER_DAY",
      pairPerMinute: "PET_PAIR_PER_MINUTE",
      setupCodeTtlSeconds: "PET_SETUP_CODE_TTL_SECONDS",
      pairRequestTtlSeconds: "PET_PAIR_REQUEST_TTL_SECONDS",
      confirmMaxWrongTries: "PET_CONFIRM_MAX_WRONG_TRIES",
      inboxWaitMaxSeconds: "PET_INBOX_WAIT_MAX_SECONDS",
      inboxTtlSeconds: "PET_INBOX_TTL_SECONDS",
      inboxMaxNotices: "PET_INBOX_MAX_NOTICES",
      heartbeatSeconds: "PET_HEARTBEAT_SECONDS",
      onlineWindowSeconds: "PET_ONLINE_WINDOW_SECONDS",
      turnClaimTtlSeconds: "PET_TURN_CLAIM_TTL_SECONDS",
      nameMaxChars: "PET_NAME_MAX_CHARS",
    };
    expect(Object.keys(names).sort()).toEqual(Object.keys(PET_LIMITS).sort());
    for (const [key, macro] of Object.entries(names)) {
      const value = PET_LIMITS[key as keyof typeof PET_LIMITS];
      expect(text, macro).toContain(`#define ${macro} ${value}\n`);
    }
    expect(text).toContain("#define PET_ADPCM_SAMPLES_PER_BLOCK 1017\n");
  });

  it("carries the listening rule: two minutes, 1 MiB, five seconds of silence", () => {
    expect(text).toContain("#define PET_RECORD_MAX_SECONDS 120\n");
    expect(text).toContain("#define PET_UPLOAD_MAX_BYTES 1048576\n");
    expect(text).toContain("#define PET_SILENCE_END_SECONDS 5\n");
  });

  it("names the headers and the audio types", () => {
    for (const [macro, value] of [
      ["PET_HEADER_TURN", "X-Pet-Turn"],
      ["PET_HEADER_RECORDED_AT", "X-Pet-Recorded-At"],
      ["PET_HEADER_OFFLINE", "X-Pet-Offline"],
      ["PET_HEADER_STATE", "X-Pet-State"],
      ["PET_HEADER_CHAT", "X-Pet-Chat"],
      ["PET_HEADER_RUN", "X-Pet-Run"],
      ["PET_HEADER_LINE", "X-Pet-Line"],
      ["PET_AUDIO_UP_CONTENT_TYPE", "audio/wav"],
      ["PET_AUDIO_DOWN_CONTENT_TYPE", "audio/L16;rate=22050"],
    ] as const) {
      expect(text, macro).toContain(`#define ${macro} "${value}"\n`);
    }
  });

  it("holds the code alphabet and the code lengths", () => {
    expect(text).toContain(
      '#define PET_CODE_ALPHABET "ABCDEFGHJKMNPQRSTUVWXYZ23456789"\n',
    );
    expect(text).toContain("#define PET_SETUP_CODE_LENGTH 10\n");
    expect(text).toContain("#define PET_CONFIRM_CODE_LENGTH 8\n");
  });

  it("has the kinds as an enum and as arrays", () => {
    expect(text).toContain("enum PetKind {");
    expect(text).toContain("PET_KIND_ASTRONAUT = 0,");
    expect(text).toContain("PET_KIND_ALIEN = 1,");
    expect(text).toContain("PET_KIND_CAT = 2,");
    expect(text).toMatch(
      /PET_KIND_IDS\[PET_KIND_COUNT\] = \{\n {2}"astronaut",\n {2}"alien",\n {2}"cat",\n\};/,
    );
    expect(text).toMatch(
      /PET_KIND_NAMES\[PET_KIND_COUNT\] = \{\n {2}"Nova",\n {2}"Zib",\n {2}"Comet",\n\};/,
    );
    expect(text).toMatch(
      /PET_KIND_DEFAULT_VOICES\[PET_KIND_COUNT\] = \{\n {2}"talia",\n {2}"darian",\n {2}"maisie",\n\};/,
    );
    expect(text).toContain("#define PET_VOICE_COUNT 6\n");
    for (const voice of [
      "talia",
      "alicia",
      "maisie",
      "darian",
      "eldrin",
      "wyatt",
    ]) {
      expect(text).toContain(`"${voice}"`);
    }
  });

  it("has the states and the notice kinds", () => {
    expect(text).toContain("PET_STATE_NEEDS_APPROVE = 2,");
    expect(text).toContain('  "needs-approve",');
    expect(text).toContain("#define PET_STATE_COUNT 4\n");
    expect(text).toContain("PET_NOTICE_KIND_APPROVAL = 1,");
    expect(text).toContain('  "settings",');
    expect(text).toContain("#define PET_NOTICE_KIND_COUNT 6\n");
  });

  it("defines every line id once, as a string of the same name", () => {
    for (const line of PET_LINES) {
      const macro = `PET_LINE_${line.id.toUpperCase().replace(/-/g, "_")}`;
      const matches = text.match(
        new RegExp(`^#define ${macro} "${line.id}"$`, "gm"),
      );
      expect(matches, line.id).toHaveLength(1);
    }
    expect(text).toContain(`#define PET_LINE_COUNT ${PET_LINES.length}\n`);
    expect(text).toContain('#define PET_LINE_CHAR_K "char-K"\n');
    expect(text).toContain(
      '#define PET_LINE_ROLE_PRODUCT_OWNER "role-product-owner"\n',
    );
  });

  it("lists the boot lines and the role ids", () => {
    const boot = PET_LINES.filter((line) => line.boot);
    expect(text).toContain(`#define PET_BOOT_LINE_COUNT ${boot.length}\n`);
    const bootBlock =
      /PET_BOOT_LINE_IDS\[PET_BOOT_LINE_COUNT\] = \{\n([\s\S]*?)\n\};/.exec(
        text,
      );
    expect(bootBlock?.[1]?.split("\n")).toHaveLength(boot.length);
    expect(text).toContain(`#define PET_ROLE_COUNT ${PET_ROLE_IDS.length}\n`);
    const roleBlock =
      /PET_ROLE_IDS\[PET_ROLE_COUNT\] = \{\n([\s\S]*?)\n\};/.exec(text);
    expect(roleBlock?.[1]?.split("\n").map((row) => row.trim())).toEqual(
      PET_ROLE_IDS.map((role) => `"${role}",`),
    );
  });

  it("has the error table in the contract's order", () => {
    expect(text).toContain("struct PetErrorInfo {");
    expect(text).toContain(
      `#define PET_ERROR_COUNT ${Object.keys(PET_ERRORS).length}\n`,
    );
    const block = /PET_ERRORS\[PET_ERROR_COUNT\] = \{\n([\s\S]*?)\n\};/.exec(
      text,
    );
    const rows = block?.[1]?.split("\n") ?? [];
    expect(rows).toHaveLength(16);
    expect(rows[0]).toBe('  {"bad_request", 400, PET_LINE_BUSY},');
    expect(rows[7]).toBe('  {"gone", 404, PET_LINE_BUSY},');
    expect(rows[9]).toBe('  {"gone", 410, PET_LINE_SETUP_REFUSED},');
    expect(rows[15]).toBe('  {"store_off", 503, PET_LINE_BUSY},');
  });

  it("uses static const arrays, never plain globals", () => {
    for (const match of text.matchAll(
      /^(?!#|\/\/|struct|enum|\s|\}|$)(.*) = \{$/gm,
    )) {
      expect(match[1], match[0]).toMatch(/^static const /);
    }
    expect(text).not.toMatch(/^const /m);
  });

  it("carries pet-usb v1: the constants, the limits and the USB ids", () => {
    for (const row of [
      "#define PET_USB_VERSION 1",
      '#define PET_USB_PREFIX "@pet1 "',
      "#define PET_USB_PREFIX_LENGTH 6",
      "#define PET_USB_MAX_LINE 512 ",
      "#define PET_USB_MAX_LINES_PER_SECOND 10",
      "#define PET_USB_BAUD 115200",
      "#define PET_USB_VENDOR_ID 0x2341",
      "#define PET_USB_PRODUCT_ID 0x0070",
      "#define PET_USB_MAX_NETWORKS 20",
      "#define PET_USB_SSID_MAX_BYTES 32",
      "#define PET_USB_PASSWORD_MIN_CHARS 8",
      "#define PET_USB_PASSWORD_MAX_CHARS 63",
      "#define PET_USB_PASSWORD_HEX_CHARS 64",
      '#define PET_USB_OPEN_PASSWORD "-" ',
      '#define PET_USB_WORD_PAIRED "paired"',
      '#define PET_USB_WORD_UNPAIRED "unpaired"',
      '#define PET_USB_WORD_OPEN "open"',
      '#define PET_USB_WORD_CLOSED "closed"',
      '#define PET_USB_WORD_LOCKED "locked"',
    ]) {
      expect(text, row).toContain(`${row}`);
    }
  });

  it("has the ops, replies, states, errors and refusals as enums and arrays", () => {
    const lists = [
      ["PetUsbOp", "PET_USB_OP", PET_USB_OPS],
      ["PetUsbReply", "PET_USB_REPLY", PET_USB_REPLY_TYPES],
      ["PetUsbState", "PET_USB_STATE", PET_USB_STATES],
      ["PetUsbError", "PET_USB_ERROR", PET_USB_ERRORS],
      ["PetUsbRefusal", "PET_USB_REFUSAL", PET_USB_REFUSALS],
    ] as const;
    for (const [type, prefix, ids] of lists) {
      expect(text).toContain(`enum ${type} {\n`);
      expect(text).toContain(`#define ${prefix}_COUNT ${ids.length}\n`);
      ids.forEach((id, i) => {
        const macro = id.toUpperCase().replace(/[^A-Z0-9]/g, "_");
        expect(text, id).toContain(`  ${prefix}_${macro} = ${i},\n`);
      });
      const block = new RegExp(
        `${prefix}_IDS\\[${prefix}_COUNT\\] = \\{\\n([\\s\\S]*?)\\n\\};`,
      ).exec(text);
      expect(block?.[1]?.split("\n").map((row) => row.trim())).toEqual(
        ids.map((id) => `"${id}",`),
      );
    }
    expect(text).toContain('  "scan-done",\n');
    expect(text).toContain("PET_USB_ERROR_SAVE_FAILED = 4,");
    expect(text).toContain("PET_USB_REFUSAL_RATE_LIMITED = 4,");
  });

  it("describes the voice pack file", () => {
    expect(text).toContain('#define PET_VOICE_PACK_MAGIC "SFVP"\n');
    expect(text).toContain("#define PET_VOICE_PACK_HEADER_BYTES 16\n");
    expect(text).toContain("#define PET_VOICE_PACK_ENTRY_BYTES 36\n");
  });
});

describe("adpcm_vectors.h", () => {
  const text = renderAdpcmVectorsHeader();

  function array(name: string): number[] {
    const block = new RegExp(
      `${name}\\[[A-Z_]+\\] = \\{\\n([\\s\\S]*?)\\n\\};`,
    ).exec(text);
    return (block?.[1] ?? "")
      .split(/[\s,]+/)
      .filter(Boolean)
      .map((token) => Number(token));
  }

  it("starts with the banner and a pragma once", () => {
    const lines = text.split("\n");
    expect(lines[0]).toBe(BANNER);
    expect(lines[1]).toBe("#pragma once");
  });

  it("states the formula in a comment and in a function", () => {
    expect(text).toContain("//   v = ((n * 97) % 4001) - 2000;");
    expect(text).toContain("//   v = v * 8 + ((n % 50 < 25) ? 3000 : -3000);");
    expect(text).toContain("static inline int16_t adpcm_vector_input(int n) {");
    expect(text).toContain("  int v = ((n * 97) % 4001) - 2000;");
    expect(text).toContain("  v = v * 8 + ((n % 50 < 25) ? 3000 : -3000);");
  });

  it("has 2100 samples, 1536 encoded bytes and 2100 decoded samples", () => {
    expect(text).toContain("#define ADPCM_VECTOR_SAMPLES 2100\n");
    expect(text).toContain("#define ADPCM_VECTOR_BLOCK_ALIGN 512\n");
    expect(text).toContain("#define ADPCM_VECTOR_ENCODED_BYTES 1536\n");
    expect(array("ADPCM_VECTOR_ENCODED")).toHaveLength(1536);
    expect(array("ADPCM_VECTOR_DECODED")).toHaveLength(ADPCM_VECTOR_SAMPLES);
  });

  it("formats the arrays sixteen values a line", () => {
    for (const name of ["ADPCM_VECTOR_ENCODED", "ADPCM_VECTOR_DECODED"]) {
      const block = new RegExp(
        `${name}\\[[A-Z_]+\\] = \\{\\n([\\s\\S]*?)\\n\\};`,
      ).exec(text);
      const rows = (block?.[1] ?? "").split("\n");
      for (const row of rows.slice(0, -1)) {
        expect(
          row.split(",").filter((cell) => cell.trim()),
          name,
        ).toHaveLength(16);
      }
      expect(
        rows
          .at(-1)
          ?.split(",")
          .filter((cell) => cell.trim()).length,
      ).toBeLessThanOrEqual(16);
    }
  });

  it("holds the decoder's output for the encoded bytes", () => {
    const encoded = Uint8Array.from(array("ADPCM_VECTOR_ENCODED"));
    const decoded = array("ADPCM_VECTOR_DECODED");
    expect([...decodeImaAdpcm(encoded, 512, ADPCM_VECTOR_SAMPLES)]).toEqual(
      decoded,
    );
  });
});

describe("usb_vectors.h", () => {
  const text = renderUsbVectorsHeader();
  const rows = (name: string): string[] => {
    const block = new RegExp(
      `${name}\\[[A-Z_]+\\] = \\{\\n([\\s\\S]*?)\\n\\};`,
    ).exec(text);
    return (block?.[1] ?? "").split("\n");
  };

  it("starts with the banner, a pragma once and the protocol header", () => {
    const lines = text.split("\n");
    expect(lines[0]).toBe(BANNER);
    expect(lines[1]).toBe("#pragma once");
    expect(text).toContain('#include "generated/protocol.h"\n');
    expect(text.endsWith("\n")).toBe(true);
  });

  it("is plain ASCII with no trailing spaces", () => {
    expect(text).toMatch(/^[\x20-\x7e\n]*$/);
    expect(text).not.toMatch(/ +\n/);
  });

  it("holds a row for every request and reply vector, in order", () => {
    expect(text).toContain(
      `#define PET_USB_REQUEST_VECTOR_COUNT ${PET_USB_REQUEST_VECTORS.length}\n`,
    );
    expect(text).toContain(
      `#define PET_USB_REPLY_VECTOR_COUNT ${PET_USB_REPLY_VECTORS.length}\n`,
    );
    expect(
      rows("PET_USB_REQUEST_VECTORS").map(
        (row) => /^ {2}\{"([^"]*)"/.exec(row)?.[1],
      ),
    ).toEqual(PET_USB_REQUEST_VECTORS.map((vector) => vector.name));
    expect(
      rows("PET_USB_REPLY_VECTORS").map(
        (row) => /^ {2}\{"([^"]*)"/.exec(row)?.[1],
      ),
    ).toEqual(PET_USB_REPLY_VECTORS.map((vector) => vector.name));
  });

  it("writes each reply line as the vector has it", () => {
    for (const vector of PET_USB_REPLY_VECTORS) {
      expect(text, vector.name).toContain(`, "${vector.line}"},\n`);
    }
  });

  it("writes a byte that is not printable ASCII as an octal escape, never a hex one", () => {
    expect(text).toContain('"@pet1 hel\\001lo"');
    expect(text).toContain('"@pet1 h\\351llo"');
    expect(text).toContain('"@pet1 hello\\011scan"');
    expect(text).not.toMatch(/\\x[0-9a-fA-F]/);
    // A question mark could start a trigraph.
    for (const row of [
      ...rows("PET_USB_REQUEST_VECTORS"),
      ...rows("PET_USB_REPLY_VECTORS"),
    ]) {
      expect(row).not.toContain("?");
    }
  });

  it("gives the decoded bytes of a name that is not UTF-8", () => {
    expect(text).toContain(
      '{"join-ssid-not-utf8", false, false, "@pet1 join fffe41 68756e7465723232 K7QXM2PA9T", "ok", "join", {0xff, 0xfe, 0x41}, 3, "hunter22", "K7QXM2PA9T", ""},',
    );
  });

  it("holds the overflow lines whole", () => {
    expect(text).toContain(
      `"@pet1 ${"a".repeat(506)}", "refused", "", {0}, 0, "", "", "unknown_op"},`,
    );
    expect(text).toContain(
      `"@pet1 ${"a".repeat(507)}", "refused", "", {0}, 0, "", "", "bad_line"},`,
    );
  });
});
